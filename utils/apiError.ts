/**
 * HTTP 상태코드를 사용자가 읽을 수 있는 문장으로 바꾼다.
 *
 * ❌ 기존: `throw new Error(\`운송비 원장 조회 실패: ${response.status}\`)`
 *    → 화면에 **"운송비 원장 조회 실패: 403"** 이 그대로 떴다.
 *      사용자는 403 이 무슨 뜻인지 알 수 없고, 무엇을 해야 하는지도 알 수 없다.
 *      (2026-09-21 대리 로그인으로 영업 담당자 화면을 보다가 발견)
 *
 * ✅ 지금: **"이 기능을 사용할 권한이 없습니다. 시스템관리자에게 권한을 요청하세요."**
 *
 * ⚠ 이 백엔드는 **토큰이 없어도 401 이 아니라 403** 을 준다.
 *   그래서 403 을 "세션 만료"로 단정하면 안 된다. 권한 문제로 안내하고,
 *   세션 만료는 인터셉터가 따로 처리한다.
 */
const STATUS_MESSAGE: Record<number, string> = {
  400: '입력값을 확인해 주세요.',
  401: '로그인이 필요합니다. 다시 로그인해 주세요.',
  403: '이 기능을 사용할 권한이 없습니다.\n시스템관리자에게 권한을 요청하세요.',
  404: '요청한 정보를 찾을 수 없습니다.\n이미 삭제되었거나 주소가 바뀌었을 수 있습니다.',
  409: '이미 처리된 건입니다. 목록을 새로고침한 뒤 다시 시도해 주세요.',
  413: '파일 크기가 너무 큽니다.',
  429: '요청이 너무 잦습니다. 잠시 후 다시 시도해 주세요.',
  500: '서버에서 오류가 발생했습니다.\n잠시 후 다시 시도하고, 계속되면 시스템관리자에게 알려 주세요.',
  502: '서버에 연결할 수 없습니다. 잠시 후 다시 시도해 주세요.',
  503: '서버 점검 중이거나 일시적으로 응답할 수 없습니다. 잠시 후 다시 시도해 주세요.',
  504: '서버 응답이 지연되고 있습니다. 잠시 후 다시 시도해 주세요.'
}

/**
 * @param status HTTP 상태코드
 * @param what   무슨 작업이었는지 (예: '운송비 원장 조회'). 앞에 붙여 맥락을 준다
 */
export function httpErrorMessage (status: number, what?: string): string {
  const base = STATUS_MESSAGE[status]
    ?? `처리 중 오류가 발생했습니다. (오류 코드 ${status})`

  // 권한·인증은 무슨 작업이었는지보다 "권한이 없다"는 사실이 중요하다.
  if (status === 401 || status === 403) { return base }

  return what ? `${what}에 실패했습니다.\n${base}` : base
}

/** `throw httpError(response, '운송비 원장 조회')` 형태로 쓴다 */
export function httpError (status: number, what?: string): Error {
  return new Error(httpErrorMessage(status, what))
}
